"""Auditable classification of every mutating HTTP route in ``src.api``."""

from dataclasses import dataclass


@dataclass(frozen=True)
class ProductionWriteEntry:
    method: str
    route: str
    category: str
    gateway_status: str
    stable_request_id: str
    authoritative_readback: str
    rollback_or_manual: str
    disposition: str


def _entry(
    method: str,
    route: str,
    category: str,
    gateway_status: str,
    *,
    stable_request_id: str = "none",
    authoritative_readback: str = "none",
    rollback_or_manual: str = "manual investigation required",
    disposition: str,
) -> ProductionWriteEntry:
    return ProductionWriteEntry(
        method=method,
        route=route,
        category=category,
        gateway_status=gateway_status,
        stable_request_id=stable_request_id,
        authoritative_readback=authoritative_readback,
        rollback_or_manual=rollback_or_manual,
        disposition=disposition,
    )


